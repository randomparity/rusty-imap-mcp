/// Extract the `Message-ID` header from raw RFC 5322 bytes.
///
/// Thin wrapper around `mail_parser` so tool handlers do not need to
/// depend on `mail_parser` directly just to read one header off a
/// freshly-built message. Returns `None` when the input is not
/// parseable or when no `Message-ID` header is present.
#[must_use]
pub fn extract_message_id(raw: &[u8]) -> Option<String> {
    crate::parse::safe_parser::safe_parse(raw)
        .ok()
        .flatten()
        .and_then(|m| m.message_id().map(ToString::to_string))
}

/// Extract the RFC 2047-decoded `Subject` from raw RFC 5322 bytes via the
/// panic-catching, size-bounded [`safe_parse`](crate::parse) path.
///
/// The returned string is the *decoded* subject (encoded-words expanded),
/// so a caller echoing it into an outbound header MUST still strip control
/// characters: a decoded encoded-word can contain bare CR/LF that
/// `mail_parser` does not neutralize, which would enable header injection
/// into a re-sent message. Returns `None` when the input is unparsable or
/// carries no `Subject`.
#[must_use]
pub fn extract_subject(raw: &[u8]) -> Option<String> {
    crate::parse::safe_parser::safe_parse(raw)
        .ok()
        .flatten()
        .and_then(|m| m.subject().map(ToString::to_string))
}

/// Sanitized outbound HTML plus the warnings raised while stripping it.
#[derive(Debug, Clone)]
pub struct OutboundHtml {
    /// Ammonia-sanitized HTML: tag-allowlisted, scripts/styles/iframes and
    /// remote content removed, `javascript:` URLs dropped. Safe to place in a
    /// `text/html` part.
    pub body_html: String,
    /// Warnings describing what the sanitizer removed or flagged (stripped
    /// scripts, remote images, hidden content, link/text mismatches), so a
    /// caller can surface that the agent's HTML was altered before sending.
    pub warnings: Vec<SecurityWarning>,
}

/// Sanitize agent-authored HTML for an *outbound* message body.
///
/// Runs the caller's HTML through the same tag-allowlist ammonia pipeline used
/// for inbound mail (`crate::html`'s `sanitize`), so the server never emits
/// agent-supplied `<script>`, event handlers, remote images, or `javascript:`
/// URLs. Only the sanitized HTML and the strip warnings are returned; the
/// inbound-only `body_text` / `anchor_hrefs` are dropped. Callers must still
/// send a `text/plain` alternative alongside the returned HTML.
///
/// # Errors
///
/// Returns [`ContentError::LimitExceeded`] when `raw` exceeds the 1 MiB HTML
/// body cap.
pub fn sanitize_outbound_html(raw: &str) -> Result<OutboundHtml, ContentError> {
    let result = crate::html::sanitize(raw.as_bytes(), Some("utf-8"))?;
    Ok(OutboundHtml {
        body_html: result.body_html,
        warnings: result.warnings,
    })
}

