#[cfg(test)]
#[expect(clippy::expect_used, reason = "tests may expect on constructed values")]
mod confusables_tests {
    use crate::confusables::CONFUSABLES;

    #[test]
    fn confusables_map_contains_cyrillic_a_to_latin_a() {
        // U+0430 CYRILLIC SMALL LETTER A → "a" (U+0061)
        let target = CONFUSABLES
            .get(&'\u{0430}')
            .expect("cyrillic a should map via TR39");
        assert_eq!(*target, "a");
    }

    #[test]
    fn confusables_map_size_nontrivial() {
        // Sanity: Unicode 16 has > 6000 MA rows.
        assert!(
            CONFUSABLES.len() > 5000,
            "confusables map is suspiciously small: {}",
            CONFUSABLES.len()
        );
    }
}

#[cfg(test)]
#[expect(clippy::unwrap_used, reason = "tests")]
mod sanitize_outbound_html_tests {
    use super::sanitize_outbound_html;

    #[test]
    fn strips_script_and_warns() {
        let out = sanitize_outbound_html("<p>hi</p><script>alert(1)</script>").unwrap();
        assert!(!out.body_html.contains("<script"));
        assert!(!out.body_html.contains("alert"));
        assert!(out.body_html.contains("hi"));
        assert!(
            !out.warnings.is_empty(),
            "stripping a script should raise a warning",
        );
    }

    #[test]
    fn drops_javascript_url() {
        let out = sanitize_outbound_html("<a href=\"javascript:alert(1)\">x</a>").unwrap();
        assert!(!out.body_html.contains("javascript:"));
    }

    #[test]
    fn strips_remote_image_src() {
        let out = sanitize_outbound_html("<img src=\"https://evil.example/track.gif\">").unwrap();
        assert!(!out.body_html.contains("evil.example"));
        assert!(!out.body_html.contains("src="));
    }

    #[test]
    fn preserves_safe_markup() {
        let out = sanitize_outbound_html("<p>Hello <strong>world</strong></p>").unwrap();
        assert!(out.body_html.contains("<strong>"));
        assert!(out.body_html.contains("world"));
    }

    #[test]
    fn rejects_oversize_input() {
        let big = "x".repeat(1024 * 1024 + 1);
        assert!(sanitize_outbound_html(&big).is_err());
    }
}

#[cfg(test)]
#[expect(clippy::expect_used, reason = "tests")]
mod extract_message_id_tests {
    use super::extract_message_id;

    #[test]
    fn extract_returns_message_id_when_header_present() {
        // Kills all three wholesale stubs at extract_message_id (None,
        // Some(""), Some("xyzzy")). A constructed message with a
        // distinctive Message-ID round-trips through mail_parser to
        // a non-empty Some that contains the id substring.
        let raw = b"From: a@example\r\n\
                    Message-ID: <abc-123@example.com>\r\n\
                    \r\n\
                    body";
        let id = extract_message_id(raw).expect("Message-ID must be extracted");
        assert!(
            id.contains("abc-123@example.com"),
            "expected id to contain abc-123@example.com, got {id:?}",
        );
    }
}
